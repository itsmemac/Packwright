#!/usr/bin/env bash
# Builds the Linux installers from a linux-x64 publish folder:
#   Packwright-v<version>-linux-x64.deb   (Debian, Ubuntu, Mint, ...)
#   Packwright-v<version>-linux-x64.rpm   (Fedora, RHEL family, openSUSE, ...)
#   Packwright-v<version>-linux-x64.pkg.tar.zst   (Arch, Manjaro, EndeavourOS, ...)
#   Packwright-v<version>-linux-x64.AppImage      (any distribution, nothing to install)
#
# Usage: installer/linux/build-packages.sh <version> <publish folder> <output folder>
# Needs dpkg-deb, rpmbuild, bsdtar, zstd, fakeroot, mksquashfs and curl
# (apt install dpkg rpm libarchive-tools zstd fakeroot squashfs-tools curl).
# The three packages put the app in /opt/packwright, add a `packwright` command and a menu entry, and are removed
# again by the normal package manager. The AppImage is one file that runs where it is.
set -euo pipefail

version="${1:?version}"
publish="$(cd "${2:?publish folder}" && pwd)"
mkdir -p "${3:?output folder}"
out="$(cd "$3" && pwd)"
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo="$(cd "$here/../.." && pwd)"
name="Packwright-v${version}-linux-x64"

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
stage="$work/stage"

install -d "$stage/opt/packwright" "$stage/usr/bin" "$stage/usr/share/applications" \
  "$stage/usr/share/icons/hicolor/512x512/apps" "$stage/usr/share/doc/packwright"
cp -a "$publish/." "$stage/opt/packwright/"
chmod 755 "$stage/opt/packwright/Packwright"
ln -s /opt/packwright/Packwright "$stage/usr/bin/packwright"
install -m 644 "$here/packwright.desktop" "$stage/usr/share/applications/packwright.desktop"
install -m 644 "$repo/src/Packwright.App/Assets/icon.png" "$stage/usr/share/icons/hicolor/512x512/apps/packwright.png"
install -m 644 "$repo/LICENSE" "$stage/usr/share/doc/packwright/copyright"
install -m 644 "$repo/THIRD_PARTY_NOTICES.md" "$stage/usr/share/doc/packwright/THIRD_PARTY_NOTICES.md"
# Everyone must be able to read the app, whatever modes the publish folder came with (a publish can leave
# libraries as rwxr--r--, which only root could load).
find "$stage" -type d -exec chmod 755 {} +
find "$stage" -type f -perm /111 -exec chmod 755 {} +
find "$stage" -type f ! -perm /111 -exec chmod 644 {} +

# ------------------------------------------------------------------ .deb
debroot="$work/deb"
cp -a "$stage" "$debroot"
install -d "$debroot/DEBIAN"
size_kb="$(du -sk "$debroot" | cut -f1)"
cat > "$debroot/DEBIAN/control" <<CONTROL
Package: packwright
Version: ${version}
Section: utils
Priority: optional
Architecture: amd64
Installed-Size: ${size_kb}
Depends: libc6, libstdc++6, libx11-6, libice6, libsm6, libfontconfig1, libssl3 | libssl3t64 | libssl1.1
Maintainer: itsmemac <noreply@users.noreply.github.com>
Homepage: https://github.com/itsmemac/Packwright
Description: PS5 package, dump and image tool
 Manage a collection of PS5 dumps and images, read PS5 packages, and build or
 convert exFAT, FFPKG, FFPFSC, ZArchive images and debug packages.
 Starts from the menu, or from a terminal as "packwright" (try "packwright help").
CONTROL
chmod 644 "$debroot/DEBIAN/control"
dpkg-deb --root-owner-group -Zxz --build "$debroot" "$out/$name.deb"

# ------------------------------------------------------------------ .rpm
top="$work/rpm"
mkdir -p "$top"/{BUILD,RPMS,SOURCES,SPECS,SRPMS}
cat > "$top/SPECS/packwright.spec" <<SPEC
Name:       packwright
Version:    ${version}
Release:    1
Summary:    PS5 package, dump and image tool
License:    GPL-3.0-only
URL:        https://github.com/itsmemac/Packwright
AutoReqProv: no
Requires:   libstdc++.so.6()(64bit), libX11.so.6()(64bit), libICE.so.6()(64bit), libSM.so.6()(64bit), libfontconfig.so.1()(64bit), libssl.so.3()(64bit)

%global debug_package %{nil}
%global __os_install_post %{nil}
%global _build_id_links none
%define _binary_payload w9.xzdio

%description
Manage a collection of PS5 dumps and images, read PS5 packages, and build or
convert exFAT, FFPKG, FFPFSC, ZArchive images and debug packages.
Starts from the menu, or from a terminal as "packwright" (try "packwright help").

%install
cp -a ${stage}/. %{buildroot}/

%files
%defattr(-,root,root,-)
/opt/packwright
/usr/bin/packwright
/usr/share/applications/packwright.desktop
/usr/share/icons/hicolor/512x512/apps/packwright.png
/usr/share/doc/packwright
SPEC
rpmbuild -bb --target x86_64 --define "_topdir $top" "$top/SPECS/packwright.spec"
cp "$top/RPMS/x86_64/packwright-${version}-1.x86_64.rpm" "$out/$name.rpm"

# ------------------------------------------------------------------ Arch .pkg.tar.zst
# Laid out the way makepkg writes one: .PKGINFO, a gzipped .MTREE of every file, then the files, owned by root.
# Built here directly so no Arch system is needed.
archroot="$work/arch"
cp -a "$stage" "$archroot"
install -Dm644 "$repo/LICENSE" "$archroot/usr/share/licenses/packwright/LICENSE"   # where Arch keeps licenses
cat > "$archroot/.PKGINFO" <<PKGINFO
# Generated by installer/linux/build-packages.sh
pkgname = packwright
pkgbase = packwright
pkgver = ${version}-1
pkgdesc = PS5 package, dump and image tool
url = https://github.com/itsmemac/Packwright
builddate = ${SOURCE_DATE_EPOCH:-$(date +%s)}
packager = itsmemac <noreply@users.noreply.github.com>
size = $(du -sb "$archroot" | cut -f1)
arch = x86_64
license = GPL-3.0-only
depend = glibc
depend = gcc-libs
depend = libx11
depend = libice
depend = libsm
depend = fontconfig
depend = openssl
PKGINFO
chmod 644 "$archroot/.PKGINFO"
fakeroot -- sh -euc '
  cd "$1"
  chown -R 0:0 .
  LANG=C bsdtar -cf - --format=mtree \
    --options="!all,use-set,type,uid,gid,mode,time,size,md5,sha256,link" .PKGINFO opt usr | gzip -c -f -n > .MTREE
  chmod 644 .MTREE
  LANG=C bsdtar -cf - .MTREE .PKGINFO opt usr | zstd -q -c -T0 -19 - > "$2"
' sh "$archroot" "$out/$name.pkg.tar.zst"

# ------------------------------------------------------------------ AppImage
# A static type 2 runtime (needs no libfuse2) followed by a squashfs of the app. The runtime is pinned and checked.
runtime_url="https://github.com/AppImage/type2-runtime/releases/download/20251108/runtime-x86_64"
runtime_sha256="2fca8b443c92510f1483a883f60061ad09b46b978b2631c807cd873a47ec260d"
runtime="$work/runtime-x86_64"
curl -fsSL --retry 3 -o "$runtime" "$runtime_url"
echo "$runtime_sha256  $runtime" | sha256sum -c --quiet -

appdir="$work/AppDir"
install -d "$appdir/usr/lib/packwright" "$appdir/usr/share/applications" "$appdir/usr/share/icons/hicolor/512x512/apps"
cp -a "$publish/." "$appdir/usr/lib/packwright/"
chmod 755 "$appdir/usr/lib/packwright/Packwright"
cat > "$appdir/AppRun" <<'APPRUN'
#!/bin/sh
# Starts Packwright from inside the AppImage; arguments (files to open, or a command such as "help") pass through.
here="$(dirname "$(readlink -f "$0")")"
exec "$here/usr/lib/packwright/Packwright" "$@"
APPRUN
chmod 755 "$appdir/AppRun"
sed -e 's|^Exec=.*|Exec=packwright %F|' "$here/packwright.desktop" > "$appdir/packwright.desktop"
cp "$appdir/packwright.desktop" "$appdir/usr/share/applications/packwright.desktop"
install -m 644 "$repo/src/Packwright.App/Assets/icon.png" "$appdir/packwright.png"
install -m 644 "$repo/src/Packwright.App/Assets/icon.png" "$appdir/usr/share/icons/hicolor/512x512/apps/packwright.png"
ln -s packwright.png "$appdir/.DirIcon"
find "$appdir" -type d -exec chmod 755 {} +
find "$appdir" -type f -perm /111 -exec chmod 755 {} +
find "$appdir" -type f ! -perm /111 -exec chmod 644 {} +
mksquashfs "$appdir" "$work/app.squashfs" -root-owned -noappend -comp zstd -quiet
cat "$runtime" "$work/app.squashfs" > "$out/$name.AppImage"
chmod 755 "$out/$name.AppImage"

echo "Built:"
ls -l "$out/$name.deb" "$out/$name.rpm" "$out/$name.pkg.tar.zst" "$out/$name.AppImage"
